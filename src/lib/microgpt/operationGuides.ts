export type GuideId = Operation['id'] | 'adam';
type Explanation = { purpose: string; formula: string; notation: string; pseudocode: string };
type Guide = { forward: Explanation; reverse?: Explanation };

function explain(
	purpose: string,
	formula: string,
	notation: string,
	pseudocode: string
): Explanation {
	return { purpose, formula, notation, pseudocode };
}

function lookup(table: 'E' | 'P'): Guide {
	const token = table === 'E';
	const row = token ? 'id' : 't';
	const out = token ? 'e' : 'p';
	const address = token ? term('id', 'ID входного символа') : term('position', 'номер позиции');
	return {
		forward: explain(
			`Блок получает ${address} и использует его как адрес строки в ${term('matrix', 'матрице')} ${table}. ${token ? 'Одинаковая буква в разных местах слова приводит к одной строке E.' : 'На одном и том же месте в разных словах модель читает одну строку P. Отсчёт начинается со знака начала слова.'} Строка целиком поступает на сложение с ${token ? 'вектором позиции' : 'вектором символа'}.`,
			`${out} = ${table}[${row}, :]\n${out}[j] = ${table}[${row}, j]`,
			`${row} выбирает строку, j обозначает столбец. Двоеточие означает «все столбцы». Каждая координата уже хранится в таблице как обучаемый ${term('weights', 'вес')}. Чтение строки возвращает ${term('embedding', 'эмбеддинг')} с одной координатой на каждый столбец. При обучении оптимизатор изменяет веса таблицы. Между обновлениями одно и то же обращение к строке возвращает тот же вектор.`,
			`получить ${row} и таблицу ${table}\nвыбрать строку с номером ${row}\nвернуть все координаты этой строки в порядке столбцов`
		),
		reverse: explain(
			`При чтении строки каждая координата результата бралась из одной ячейки ${table}. Поэтому обратный проход направляет её ${term('gradient', 'градиент')} по тому же адресу. ${token ? 'Если символ встречался несколько раз, вклады всех его вхождений складываются в общей строке.' : 'Номер позиции определяет, в какой строке P накопить вклад. Градиент входного вектора уже учитывает все пути от этой позиции к ошибке.'}`,
			`g(${table})[${row}, j] += g(${out})[j]`,
			`При сложении векторов символа и позиции оба получили один и тот же входящий градиент. Здесь ${row} служит адресом. Остальные строки получают вклады при обращении к ним из других позиций.`,
			`взять адрес ${row}, сохранённый при прямом проходе\nдля каждого столбца j:\n    прибавить g(${out})[j] к градиенту ячейки ${table}[${row}, j]`
		)
	};
}

function addition(left: string, right: string, out: string, purpose: string): Guide {
	return {
		forward: explain(
			purpose,
			`${out}[j] = ${left}[j] + ${right}[j]`,
			`У обоих входов одинаковое число координат. Номер j выбирает одно и то же место в каждом ${term('vector', 'векторе')}. Выход сохраняет их размерность.`,
			`для каждой координаты j:\n    сложить ${left}[j] и ${right}[j]\n    записать сумму в ${out}[j]\nвернуть ${out}`
		),
		reverse: explain(
			`Прибавка к любому слагаемому увеличивает сумму на такую же величину. Поэтому вклад от суммы передаётся по обеим входным ветвям целиком.`,
			`g(${left})[j] += g(${out})[j]\ng(${right})[j] += g(${out})[j]`,
			`Если вход используют ещё и другие операции, их вклады в его ${term('gradient', 'градиент')} складываются. Так учитываются все пути от входа к ошибке слова.`,
			`для каждой координаты j:\n    взять градиент выхода ${out}[j]\n    прибавить его к градиенту ${left}[j]\n    прибавить его к градиенту ${right}[j]`
		)
	};
}

function normalize(x: string, y: string, context: string): Guide {
	return {
		forward: explain(
			`${context} ${term('rmsNorm', 'RMSNorm')} вычисляет общий масштаб по координатам одной позиции и делит каждую координату на него.`,
			`s = √(ε + (Σⱼ ${x}[j]²) / D)\n${y}[j] = ${x}[j] / s`,
			`D — число координат входа ${x}. Квадраты учитывают величину положительных и отрицательных чисел. Постоянная ε = 10⁻⁵ сохраняет положительный знаменатель даже при нулевом входе.`,
			`найти среднее квадратов координат ${x}\ns ← корень из (среднее + ε)\nдля каждого j: ${y}[j] ← ${x}[j] / s\nвернуть ${y}`
		),
		reverse: explain(
			`Изменение одной координаты ${x} влияет и на числитель этой координаты, и на общий делитель всех выходов. Для обратного прохода нужны оба вклада.`,
			`c = (Σₖ g(${y})[k] · ${x}[k]) / D\ng(${x})[j] += g(${y})[j] / s − ${x}[j] · c / s³`,
			`s — делитель прямого прохода, D — ширина входа. Величина c собирает влияние всех выходов через делитель. Первое слагаемое учитывает прямой путь через числитель.`,
			`взять вход ${x} и делитель s\nc ← среднее произведений g(${y})[k] и ${x}[k]\nдля каждого j:\n    прибавить g(${y})[j] / s − ${x}[j] · c / s³ к g(${x})[j]`
		)
	};
}

function linear(w: string, x: string, y: string, purpose: string): Guide {
	return {
		forward: explain(
			purpose,
			`${y} = ${w} · ${x}\n${y}[i] = Σⱼ ${w}[i, j] · ${x}[j]`,
			`Строка i матрицы ${w} задаёт одну выходную координату, столбец j соответствует входной координате. Строка весов и входной вектор имеют одинаковую длину. Их ${term('dotProduct', 'скалярное произведение')} складывает вклады всех входов с весами этой строки.`,
			`для каждой строки i матрицы ${w}:\n    сумма ← 0\n    для каждого столбца j:\n        сумма ← сумма + ${w}[i, j] · ${x}[j]\n    ${y}[i] ← сумма\nвернуть ${y}`
		),
		reverse: explain(
			`В прямом проходе ${w} связывала вход ${x} с выходом ${y}. Теперь по каждой такой связи вычисляются два вклада. Один идёт к входу и позволяет продолжить обратный проход. Другой накапливается для обновления веса.`,
			`g(${x})[j] += Σᵢ ${w}[i, j] · g(${y})[i]\ng(${w})[i, j] += g(${y})[i] · ${x}[j]`,
			`Для входной координаты j суммируются вклады всех выходов i. Это и есть умножение на ${term('transpose', 'транспонированную матрицу')}. Её строки и столбцы меняются местами. Для веса используется вход прямого прохода. Одна матрица работает на всех позициях, поэтому их вклады в её градиент складываются.`,
			`для каждого выхода i и входа j:\n    прибавить ${w}[i, j] · g(${y})[i] к g(${x})[j]\n    прибавить ${x}[j] · g(${y})[i] к g(${w})[i, j]`
		)
	};
}

function softmax(x: string, y: string, purpose: string, indices: string): Guide {
	return {
		forward: explain(
			purpose,
			`M = max(${x})\na[i] = exp(${x}[i] − M)\n${y}[i] = a[i] / Σₖ a[k]`,
			`Индексы i и k перебирают ${indices}. ${term('exponential', 'Экспонента exp')} переводит оценки в положительные числа. После вычитания максимума все показатели степени меньше или равны нулю, поэтому экспоненты помещаются в диапазон от нуля до единицы. Общий множитель exp(−M) сокращается при делении на сумму. После деления сумма долей равна единице.`,
			`найти максимальную оценку M\nдля каждого i: a[i] ← exp(${x}[i] − M)\nS ← сумма всех a[i]\nдля каждого i: ${y}[i] ← a[i] / S\nвернуть ${y}`
		),
		reverse: explain(
			`У всех выходов ${term('softmax', 'softmax')} общий знаменатель. Изменение одной оценки меняет доли остальных вариантов. Поэтому градиент входной оценки зависит от всех выходных градиентов.`,
			`c = Σₖ ${y}[k] · g(${y})[k]\ng(${x})[i] += ${y}[i] · (g(${y})[i] − c)`,
			`c — среднее входящих градиентов с весами ${y} из прямого прохода. Оно вычисляется один раз для набора, в котором softmax сравнивал ${indices}.`,
			`c ← сумма произведений ${y}[k] и g(${y})[k]\nдля каждого i:\n    прибавить ${y}[i] · (g(${y})[i] − c) к g(${x})[i]`
		)
	};
}

