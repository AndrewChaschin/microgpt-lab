export type GuideId = Operation['id'] | 'adam';
type Explanation = { purpose: string; formula: string; notation: string; pseudocode: string };
type Guide = { forward: Explanation; reverse?: Explanation };

function explain(
	purpose: string,
	formula: string,
	notation: string,
	pseudocode: string
): Explanation {
	return { purpose, formula, notation, pseudocode };
}

function lookup(table: 'E' | 'P'): Guide {
	const token = table === 'E';
	const row = token ? 'id' : 't';
	const index = token ? '\\mathrm{id}' : 't';
	const out = token ? 'e' : 'p';

	return {
		forward: explain(
			token
				? `У каждой буквы есть своя строка в E. Представьте карточку, которую дополняют после каждого упражнения. Когда один и тот же символ встречается в разных словах, все эти примеры помогают настроить его ${term('embedding', 'числовое представление')}. Так выученное на слове «кот» может пригодиться при чтении слова «котёнок».`
				: `Во всех словах для позиции 2 используется одна строка P. Обучение на разных буквах в этой позиции меняет общие настройки. Благодаря этому ${term('positionEmbedding', 'вектор позиции')} может передавать закономерности, связанные с местом в слове, даже когда меняется сама буква.`,
			String.raw`${out}_j=${table}_{${index},j}`,
			String.raw`$${table}$ — таблица обучаемых ${term('weights', 'весов')}. $${index}$ выбирает строку по ${token ? 'номеру символа' : 'позиции в слове'}, а $j$ — столбец. $${out}_j$ — значение этой ячейки. Сначала в ячейках стоят небольшие случайные числа. После прогноза ${term('adam', 'Adam')} корректирует их с учётом ошибки. Так модель учится сочетать признаки, полезные для продолжения слова.`,
			`получить ${row} и таблицу ${table}\nвыбрать строку с номером ${row}\nвернуть все координаты этой строки в порядке столбцов`
		),
		reverse: explain(
			token
				? 'В первой и последней «а» слова «мама» использована одна строка E. Если обе позиции подсказывают увеличить её вес, их вклады усилят друг друга. Если подсказывают противоположное, часть вклада погасится.'
				: 'У первой и последней «а» в «мама» разные строки P. Поэтому обучение может скорректировать подсказку для позиции 2 отдельно от позиции 4. Когда в следующем слове встретится позиция 2, модель прочитает уже обновлённую строку.',
			String.raw`g(${table})_{${index},j}\mathrel{+\!=}g(${out})_j`,
			String.raw`$${index}$ — ${token ? 'номер символа' : 'позиция в слове'}, $j$ — номер координаты. $g(${out})_j$ — вклад от прочитанной координаты, $g(${table})_{${index},j}$ — градиент ячейки, из которой её взяли. Каждое обращение к ячейке добавляет свой вклад.`,
			`взять адрес ${row}, сохранённый при прямом проходе\nдля каждого столбца j:\n    прибавить g(${out})[j] к градиенту ячейки ${table}[${row}, j]`
		)
	};
}

function addition(left: string, right: string, out: string, purpose: string): Guide {
	return {
		forward: explain(
			purpose,
			String.raw`${out}_j=${left}_j+${right === 'c₂' ? '(c_2)' : right}_j`,
			String.raw`$${left}$ и $${right}$ — входные ${term('vector', 'векторы')}, $${out}$ — их сумма. Индекс $j$ выбирает одну и ту же координату во всех трёх векторах. Знак второго слагаемого определяет, увеличится эта координата или уменьшится.`,
			`для каждой координаты j:\n    сложить ${left}[j] и ${right}[j]\n    записать сумму в ${out}[j]\nвернуть ${out}`
		),
		reverse: explain(
			`Если одну координату любого слагаемого увеличить на 0,1, та же координата суммы вырастет на 0,1. Так ошибка прогноза даёт подсказку обеим ветвям. Дальше каждая прослеживает, какие её собственные веса могли вызвать это изменение.`,
			String.raw`g(${left})_j\mathrel{+\!=}g(${out})_j
g(${right})_j\mathrel{+\!=}g(${out})_j`,
			String.raw`$g(${out})_j$ — градиент по координате $j$ суммы. $g(${left})_j$ и $g(${right})_j$ — градиенты по соответствующим координатам двух слагаемых. Каждое получает весь вклад от суммы.`,
			`для каждой координаты j:\n    взять градиент выхода ${out}[j]\n    прибавить его к градиенту ${left}[j]\n    прибавить его к градиенту ${right}[j]`
		)
	};
}

function normalize(x: string, y: string, context: string): Guide {
	const vectors = `$${x}$ — входной вектор, $${y}$ — вектор после нормировки. $${x}_j$ и $${y}_j$ — их координаты с номером $j$.`;
	const size = `$D$ — число координат в векторе. Здесь $D = ${width}$.`;
	return {
		forward: explain(
			context,
			String.raw`s=\sqrt{\varepsilon+\frac{1}{D}\sum_{j=0}^{D-1}${x}_j^2}
${y}_j=\frac{${x}_j}{s}`,
			[
				vectors,
				size,
				`$j$ — номер координаты от $0$ до $${width - 1}$. Знак $\\sum$ означает, что квадраты складывают по всем этим координатам.`,
				'$s$ — общий делитель для всех координат этой позиции.',
				'$\\varepsilon = 10^{-5}$ — малая добавка, которая сохраняет делитель положительным, даже если весь вход равен нулю.'
			].join('\n'),
			`найти среднее квадратов координат ${x}\ns ← корень из (среднее + ε)\nдля каждого j: ${y}[j] ← ${x}[j] / s\nвернуть ${y}`
		),
		reverse: explain(
			'Если увеличить модуль одной координаты, вырастет общий делитель. Поэтому могут измениться даже те выходы, чьи входные числа остались прежними. Чтобы оценить влияние этой координаты на ошибку, приходится учитывать все выходы.',
			String.raw`c=\frac{1}{D}\sum_{k=0}^{D-1}g(${y})_k\,${x}_k
g(${x})_j\mathrel{+\!=}\frac{g(${y})_j}{s}-\frac{${x}_j\,c}{s^3}`,
			[
				vectors,
				size,
				`$j$ — номер выбранной координаты. Индекс $k$ перебирает все координаты от $0$ до $${width - 1}$, а $\\sum$ складывает их вклады.`,
				'$s$ — общий делитель, сохранённый при прямом проходе.',
				`$g(${y})$ и $g(${x})$ — ${term('gradient', 'градиенты')} средней ошибки слова по выходу и по входу. Нижний индекс выбирает координату градиента.`,
				'$c$ — среднее произведений координат выходного градиента и входа. Через него учитывается влияние общего делителя.'
			].join('\n'),
			`взять вход ${x} и делитель s\nc ← среднее произведений g(${y})[k] и ${x}[k]\nдля каждого j:\n    прибавить g(${y})[j] / s − ${x}[j] · c / s³ к g(${x})[j]`
		)
	};
}

export function matrixSymbol(w: string): string {
	return (
		({ Wq: 'W_q', Wk: 'W_k', Wv: 'W_v', 'W₁': 'W_1', 'W₂': 'W_2' } as Record<string, string>)[w] ??
		w
	);
}

function linear(w: string, x: string, y: string, purpose: string): Guide {
	const matrix = matrixSymbol(w);
	const output = y === 'c₂' ? '(c_2)' : y;
	return {
		forward: explain(
			purpose,
			String.raw`${y}=${matrix}\,${x}
${output}_i=\sum_j (${matrix})_{ij}\,${x}_j`,
			String.raw`$${x}_j$ — входная координата с номером $j$, $${output}_i$ — выходная с номером $i$. $(${matrix})_{ij}$ — вес, связывающий их. При весе $-2$ увеличение одного входа на $0{,}1$ уменьшит этот выход на $0{,}2$. Знак $\sum_j$ означает ${term('summation', 'суммирование')} вкладов всех входов в один выход. Так получается ${term('dotProduct', 'скалярное произведение')}.`,
			`для каждой строки i матрицы ${w}:\n    сумма ← 0\n    для каждого столбца j:\n        сумма ← сумма + ${w}[i, j] · ${x}[j]\n    ${y}[i] ← сумма\nвернуть ${y}`
		),
		reverse: explain(
			`Если входная координата на этой позиции равна нулю, изменение умножающего её веса здесь ничего не изменит. Поэтому эта позиция даст нулевой вклад в его градиент. В другой позиции тот же вес может получить сильный сигнал. Так обучение использует сведения о том, какие входы действительно участвовали в прогнозе.`,
			String.raw`g(${x})_j\mathrel{+\!=}\sum_i (${matrix})_{ij}\,g(${y})_i
g(${matrix})_{ij}\mathrel{+\!=}g(${y})_i\,${x}_j`,
			String.raw`$${x}_j$ — координата входа $j$, $g(${y})_i$ — градиент по выходу $i$. Вес $(${matrix})_{ij}$ передаёт часть сигнала от этого выхода ко входу. В $g(${x})_j$ складываются сигналы от всех выходов. Это умножение на ${term('transpose', 'транспонированную матрицу')}. В $g(${matrix})_{ij}$ накапливаются вклады всех позиций, где использовали этот вес.`,
			`для каждого выхода i и входа j:\n    прибавить ${w}[i, j] · g(${y})[i] к g(${x})[j]\n    прибавить ${x}[j] · g(${y})[i] к g(${w})[i, j]`
		)
	};
}

function softmax(x: string, y: string, purpose: string, indices: string): Guide {
	return {
		forward: explain(
			purpose,
			String.raw`M=\max_k ${x}_k
a_i=\exp(${x}_i-M)
${y}_i=\frac{a_i}{\sum_k a_k}`,
			String.raw`$${x}_i$ — оценка варианта $i$. Индекс $k$ перебирает ${indices}, а $M$ — наибольшая из их оценок. $a_i$ — результат ${term('exponential', 'экспоненты')} $\exp$ после вычитания $M$. Наибольшая оценка даёт $a_i=1$, остальные — не больше единицы. Деление на сумму $\sum_k a_k$ превращает $a_i$ в долю $${y}_i$.`,
			`найти максимальную оценку M\nдля каждого i: a[i] ← exp(${x}[i] − M)\nS ← сумма всех a[i]\nдля каждого i: ${y}[i] ← a[i] / S\nвернуть ${y}`
		),
		reverse: explain(
			`Если увеличить сразу все оценки на одну величину, доли сохранятся. Имеет значение, насколько оценка одного варианта должна измениться относительно остальных. Поэтому при обратном проходе из сигнала для каждого варианта вычитается общее взвешенное среднее.`,
			String.raw`c=\sum_k ${y}_k\,g(${y})_k
g(${x})_i\mathrel{+\!=}${y}_i\bigl(g(${y})_i-c\bigr)`,
			String.raw`$${y}_i$ — доля варианта $i$, $g(${y})_i$ — градиент по этой доле, $g(${x})_i$ — по исходной оценке. Индекс $k$ перебирает ${indices}. Их доли служат весами в среднем $c$. Разность $g(${y})_i-c$ показывает, как сигнал этого варианта отличается от среднего.`,
			`c ← сумма произведений ${y}[k] и g(${y})[k]\nдля каждого i:\n    прибавить ${y}[i] · (g(${y})[i] − c) к g(${x})[i]`
		)
	};
}

