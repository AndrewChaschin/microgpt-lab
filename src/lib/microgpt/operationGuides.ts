export function operationExplanation(id: GuideId, backward: boolean): Explanation {
	const guide = guides[id];
	if (!backward) return guide.forward;
	if (!guide.reverse) throw new Error('Обратный проход отсутствует у ' + id);
	return guide.reverse;
}
