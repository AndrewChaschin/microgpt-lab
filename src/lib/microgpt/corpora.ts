function createCorpus(words: string[], validationWords: string[]) {
	const alphabet = [...new Set(words.join(''))].sort();
	return {
		words,
		validationWords,
		alphabet,
		boundary: alphabet.length,
		vocabulary: [...alphabet, '◇']
	};
}

export const corpora = {
	ru: createCorpus(russianWords, russianValidationWords),
	en: createCorpus(englishWords, englishValidationWords)
};
export type Corpus = (typeof corpora)[keyof typeof corpora];
